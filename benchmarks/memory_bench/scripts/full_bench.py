"""Full memory_bench launcher.

Generates a reproducible TOML suite for the full provider × benchmark matrix and
Defaults are tuned for this workstation's honest Gemma-only runs: worker count
comes from repo `.env`/`MEMORY_BENCH_WORKERS` (falling back to 20), and reader
and judge default to the same configured Gemma model.
"""

