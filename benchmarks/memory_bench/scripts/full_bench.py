import os
import subprocess
import sys
from pathlib import Path

BENCHMARKS = ("agent_quality", "locomo", "longmemeval", "beam", "memoryarena", "evomembench")
DEFAULT_GEMMA_MODEL = "gemma-4-31B-it"
DEFAULT_WORKERS = 20
