def _toml_str(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def build_suite_toml(
    *,
    max_parallel: int = DEFAULT_WORKERS,
    reader_model: str = DEFAULT_GEMMA_MODEL,
    judge_model: str = DEFAULT_GEMMA_MODEL,
    reader_max_tokens: int = 2048,
    max_episodes: int = 0,
    max_probes_per_episode: int = 0,
    out_dir: str = "runs/memory_bench_full",
    cache_dir: str = ".memory_bench_cache",
    include_agentic: bool = True,
    use_llm_judge: bool = True,
    recall_k: int = 10,
    max_context_tokens: int = 4000,
) -> str:
    """Return a full-suite TOML string for memory_bench.

    `max_episodes=0` and `max_probes_per_episode=0` mean full datasets.  Set
    small positive values for smoke tests without changing the matrix shape.
    """
    if max_parallel < 1:
        raise ValueError("max_parallel must be >= 1")
    if reader_max_tokens < 1:
        raise ValueError("reader_max_tokens must be >= 1")

    benchmarks = BENCHMARKS if include_agentic else BENCHMARKS[:3]
    benchmark_list = ", ".join(_toml_str(name) for name in benchmarks)
    use_llm = "true" if use_llm_judge else "false"

    lines = [
        "# Generated by: python -m memory_bench.scripts.full_bench",
        f"out_dir = {_toml_str(out_dir)}",
        f"cache_dir = {_toml_str(cache_dir)}",
        "",
        "[responder]",
        f"model = {_toml_str(reader_model)}",
        "temperature = 0.0",
        f"max_tokens = {reader_max_tokens}",
        "",
        "[judge]",
        f"llm_judge_model = {_toml_str(judge_model)}",
        f"use_llm_judge = {use_llm}",
        "",
        "[limits]",
        f"recall_k = {recall_k}",
        f"max_context_tokens = {max_context_tokens}",
        f"max_episodes = {max_episodes}",
        f"max_probes_per_episode = {max_probes_per_episode}",
        "seed = 0",
        f"max_parallel = {max_parallel}",
        "redo_existing = true",
        "",
        "[dataset]",
        f"max_episodes = {max_episodes}",
        f"max_probes_per_episode = {max_probes_per_episode}",
        "",
        "[suite]",
        f"benchmarks = [{benchmark_list}]",
        "",
    ]

    for provider in PROVIDERS:
        lines.extend(
            [
                "[[provider]]",
                f"id = {_toml_str(str(provider['id']))}",
                f"adapter = {_toml_str(str(provider['adapter']))}",
            ]
        )
        for key, value in provider.items():
            if key in {"id", "adapter"}:
                continue
            if isinstance(value, bool):
                rendered = "true" if value else "false"
            elif isinstance(value, int):
                rendered = str(value)
            else:
                rendered = _toml_str(str(value))
            lines.append(f"{key} = {rendered}")
        lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _load_repo_env() -> None:
    """Load repo .env so script defaults honor LLM_MODEL and worker knobs."""
    root = _repo_root()
    try:
        from lethyx.env import load_env

        load_env(repo_root=root, override=True)
        return
    except Exception:
        pass
    env_path = root / ".env"
    if not env_path.is_file():
        return
    for raw_line in env_path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        os.environ[key] = value


def _child_env() -> dict[str, str]:
    env = dict(os.environ)
    root = _repo_root()
    additions = [str(root / "benchmarks"), str(root / "src")]
    existing = env.get("PYTHONPATH", "")
    if existing:
        additions.append(existing)
    env["PYTHONPATH"] = os.pathsep.join(additions)
    return env


def _default_workers() -> int:
    raw = os.getenv("MEMORY_BENCH_WORKERS", "").strip()
    if raw:
        try:
            return max(1, int(raw))
        except ValueError:
            pass
    return DEFAULT_WORKERS


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Generate and run the full memory_bench matrix")
    parser.add_argument(
        "--workers",
        type=int,
        default=_default_workers(),
        help="ThreadPool workers (default: 20 or MEMORY_BENCH_WORKERS)",
    )
    parser.add_argument("--reader-model", default=os.getenv("LLM_MODEL", DEFAULT_GEMMA_MODEL))
    parser.add_argument(
        "--judge-model",
        default=os.getenv("MEMORY_BENCH_JUDGE_MODEL", os.getenv("LLM_MODEL", DEFAULT_GEMMA_MODEL)),
    )
    parser.add_argument(
        "--reader-max-tokens",
        type=int,
        default=int(os.getenv("MEMORY_BENCH_READER_MAX_TOKENS", "2048")),
    )
    parser.add_argument("--max-episodes", type=int, default=0)
    parser.add_argument("--max-probes-per-episode", type=int, default=0)
    parser.add_argument("--out", default="runs/memory_bench_full")
    parser.add_argument("--cache-dir", default=".memory_bench_cache")
    parser.add_argument("--suite-path", default=".memory_bench_cache/full_bench_suite.toml")
    parser.add_argument(
        "--no-agentic",
        action="store_true",
        help="Only run recall benchmarks: locomo, longmemeval, beam",
    )
    parser.add_argument("--no-llm-judge", action="store_true")
    parser.add_argument(
        "--dry-run", action="store_true", help="Write suite and print command without running"
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    _load_repo_env()
    parser = build_parser()
    args = parser.parse_args(argv)
    suite = build_suite_toml(
        max_parallel=args.workers,
        reader_model=args.reader_model,
        judge_model=args.judge_model,
        reader_max_tokens=args.reader_max_tokens,
        max_episodes=args.max_episodes,
        max_probes_per_episode=args.max_probes_per_episode,
        out_dir=args.out,
        cache_dir=args.cache_dir,
        include_agentic=not args.no_agentic,
        use_llm_judge=not args.no_llm_judge,
    )
    suite_path = Path(args.suite_path)
    suite_path.parent.mkdir(parents=True, exist_ok=True)
    suite_path.write_text(suite, encoding="utf-8")

    cmd = [sys.executable, "-m", "memory_bench", "run", "--suite", str(suite_path)]
    print(f"Wrote suite: {suite_path}")
    print("Run command:", " ".join(cmd))
    if args.dry_run:
        return 0
    return subprocess.call(cmd, env=_child_env())


if __name__ == "__main__":
    raise SystemExit(main())
