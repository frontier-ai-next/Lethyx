"""Small quality-benchmark launcher for Lethyx memory comparisons.

Default run is intentionally simple and dataset-free: it runs the built-in
`agent_quality` benchmark across Lethyx's three selected backends, direct native
backend baselines, and pure-Python controls.  Add `--external` when local
LoCoMo/LongMemEval/BEAM/etc. datasets are installed.
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path

DEFAULT_BENCHMARKS = ("agent_quality",)
EXTERNAL_BENCHMARKS = ("locomo", "longmemeval", "beam", "memoryarena", "evomembench")

QUALITY_PROVIDERS: tuple[dict[str, object], ...] = (
    {"id": "lethyx-mempalace", "adapter": "lethyx", "backend": "mempalace"},
    {"id": "lethyx-hindsight", "adapter": "lethyx", "backend": "hindsight"},
    {"id": "lethyx-mnemosyne", "adapter": "lethyx", "backend": "mnemosyne"},
    {"id": "raw-mempalace", "adapter": "raw-mempalace"},
    {"id": "raw-mnemosyne", "adapter": "raw-mnemosyne"},
    {"id": "baseline-no-memory", "adapter": "no_memory"},
    {"id": "baseline-full-context", "adapter": "full_context"},
    {"id": "baseline-bm25", "adapter": "bm25"},
)

OPTIONAL_NATIVE_PROVIDERS: tuple[dict[str, object], ...] = (
    {"id": "lethyx-mempalace-native", "adapter": "lethyx", "backend": "mempalace", "native": True},
    {"id": "lethyx-mnemosyne-native", "adapter": "lethyx", "backend": "mnemosyne", "native": True},
)

RAW_HINDSIGHT_PROVIDER = {
    "id": "raw-hindsight",
    "adapter": "raw-hindsight",
    "embedded": False,
}


def _toml_str(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _render_provider(provider: dict[str, object]) -> list[str]:
    lines = [
        "[[provider]]",
        f"id = {_toml_str(str(provider['id']))}",
        f"adapter = {_toml_str(str(provider['adapter']))}",
    ]
    for key, value in provider.items():
        if key in {"id", "adapter"}:
            continue
        if isinstance(value, bool):
            rendered = "true" if value else "false"
        elif isinstance(value, int):
            rendered = str(value)
        else:
            rendered = _toml_str(str(value))
        lines.append(f"{key} = {rendered}")
    lines.append("")
    return lines


def build_suite_toml(
    *,
    max_parallel: int = 1,
    reader_model: str = "",
    judge_model: str = "",
    reader_max_tokens: int = 768,
    max_episodes: int = 0,
    max_probes_per_episode: int = 0,
    out_dir: str = "runs/memory_bench_quality",
    cache_dir: str = ".memory_bench_cache",
    include_external: bool = False,
    include_native_lethyx: bool = False,
    include_raw_hindsight: bool = False,
    use_llm_judge: bool = False,
    recall_k: int = 5,
    max_context_tokens: int = 2000,
) -> str:
    """Return a compact quality-suite TOML string.

    Defaults are safe for quick local checks: deterministic judges where
    possible, one worker, and only the built-in dataset-free benchmark.
    """
    if max_parallel < 1:
        raise ValueError("max_parallel must be >= 1")
    if reader_max_tokens < 1:
        raise ValueError("reader_max_tokens must be >= 1")

    benchmarks = DEFAULT_BENCHMARKS + (EXTERNAL_BENCHMARKS if include_external else ())
    providers = list(QUALITY_PROVIDERS)
    if include_native_lethyx:
        providers.extend(OPTIONAL_NATIVE_PROVIDERS)
    if include_raw_hindsight:
        providers.append(dict(RAW_HINDSIGHT_PROVIDER))

    model = reader_model or os.getenv("LLM_MODEL", "")
    judge = judge_model or os.getenv("MEMORY_BENCH_JUDGE_MODEL", model)
    benchmark_list = ", ".join(_toml_str(name) for name in benchmarks)

    lines = [
        "# Generated by: python -m memory_bench.scripts.quality_bench",
        f"out_dir = {_toml_str(out_dir)}",
        f"cache_dir = {_toml_str(cache_dir)}",
        "",
        "[responder]",
        f"model = {_toml_str(model)}",
        "temperature = 0.0",
        f"max_tokens = {reader_max_tokens}",
        "",
        "[judge]",
        f"llm_judge_model = {_toml_str(judge)}",
        f"use_llm_judge = {'true' if use_llm_judge else 'false'}",
        "",
        "[limits]",
        f"recall_k = {recall_k}",
        f"max_context_tokens = {max_context_tokens}",
        f"max_episodes = {max_episodes}",
        f"max_probes_per_episode = {max_probes_per_episode}",
        "seed = 0",
        f"max_parallel = {max_parallel}",
        "redo_existing = true",
        "",
        "[dataset]",
        f"max_episodes = {max_episodes}",
        f"max_probes_per_episode = {max_probes_per_episode}",
        "",
        "[suite]",
        f"benchmarks = [{benchmark_list}]",
        "",
    ]
    for provider in providers:
        lines.extend(_render_provider(provider))
    return "\n".join(lines).rstrip() + "\n"


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[3]


def _load_repo_env() -> None:
    """Load repo .env so script defaults honor LLM_MODEL and worker knobs."""
    root = _repo_root()
    try:
        from lethyx.env import load_env

        load_env(repo_root=root, override=True)
        return
    except Exception:
        pass
    env_path = root / ".env"
    if not env_path.is_file():
        return
    for raw_line in env_path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
            value = value[1:-1]
        os.environ[key] = value


def _child_env() -> dict[str, str]:
    env = dict(os.environ)
    root = _repo_root()
    additions = [str(root / "benchmarks"), str(root / "src")]
    existing = env.get("PYTHONPATH", "")
    if existing:
        additions.append(existing)
    env["PYTHONPATH"] = os.pathsep.join(additions)
    return env


def _default_workers() -> int:
    raw = os.getenv("MEMORY_BENCH_WORKERS", "").strip()
    if raw:
        try:
            return max(1, int(raw))
        except ValueError:
            pass
    return 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Run a small memory quality matrix")
    parser.add_argument("--workers", type=int, default=_default_workers())
    parser.add_argument("--reader-model", default=os.getenv("LLM_MODEL", ""))
    parser.add_argument(
        "--judge-model", default=os.getenv("MEMORY_BENCH_JUDGE_MODEL", os.getenv("LLM_MODEL", ""))
    )
    parser.add_argument("--reader-max-tokens", type=int, default=768)
    parser.add_argument("--max-episodes", type=int, default=0)
    parser.add_argument("--max-probes-per-episode", type=int, default=0)
    parser.add_argument("--out", default="runs/memory_bench_quality")
    parser.add_argument("--cache-dir", default=".memory_bench_cache")
    parser.add_argument("--suite-path", default=".memory_bench_cache/quality_bench_suite.toml")
    parser.add_argument(
        "--external", action="store_true", help="Include external dataset benchmarks when installed"
    )
    parser.add_argument(
        "--include-native-lethyx",
        action="store_true",
        help="Also run native Lethyx MemPalace/Mnemosyne providers",
    )
    parser.add_argument(
        "--include-raw-hindsight",
        action="store_true",
        help="Also run direct Hindsight; requires a configured server/client",
    )
    parser.add_argument(
        "--llm-judge", action="store_true", help="Use LLM judge where benchmark default asks for it"
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="Write suite and print command without running"
    )
    return parser


def main(argv: list[str] | None = None) -> int:
    _load_repo_env()
    parser = build_parser()
    args = parser.parse_args(argv)
    suite = build_suite_toml(
        max_parallel=args.workers,
        reader_model=args.reader_model,
        judge_model=args.judge_model,
        reader_max_tokens=args.reader_max_tokens,
        max_episodes=args.max_episodes,
        max_probes_per_episode=args.max_probes_per_episode,
        out_dir=args.out,
        cache_dir=args.cache_dir,
        include_external=args.external,
        include_native_lethyx=args.include_native_lethyx,
        include_raw_hindsight=args.include_raw_hindsight,
        use_llm_judge=args.llm_judge,
    )
    suite_path = Path(args.suite_path)
    suite_path.parent.mkdir(parents=True, exist_ok=True)
    suite_path.write_text(suite, encoding="utf-8")

    cmd = [sys.executable, "-m", "memory_bench", "run", "--suite", str(suite_path)]
    print(f"Wrote suite: {suite_path}")
    print("Run command:", " ".join(cmd))
    if args.dry_run:
        return 0
    return subprocess.call(cmd, env=_child_env())


if __name__ == "__main__":
    raise SystemExit(main())
